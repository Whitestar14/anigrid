/** One empty column between glyphs, in bitmap units. */
export const PIXEL_TRACKING = 1;
/** The glyph grid's height in bitmap units. */
export const PIXEL_ROWS = 7;

export const hasPixelGlyph = (char: string) => char in GLYPHS;

/** True when every character in `text` can be drawn as bitmap. */
export const isPixelText = (text: string) =>
  [...text.toUpperCase()].every(hasPixelGlyph);

/**
 * Each row's horizontal runs are merged into one rectangle, and all of them
 * become a single `<path>`. Fewer nodes matters because this sits inside the
 * tree `html-to-image` walks on every export.
 */
const glyphPath = (
  char: string,
  originX: number,
): { d: string; width: number } => {
  const glyph = GLYPHS[char];
  if (!glyph) return { d: "", width: 0 };

  let d = "";
  const width = glyph[0].length;

  glyph.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== "#") continue;

      let run = 1;
      while (row[x + run] === "#") run++;

      d += `M${originX + x} ${y}h${run}v1h-${run}z`;
      x += run - 1;
    }
  });

  return { d, width };
};

/** Width of a string in bitmap units. */
export const pixelTextUnits = (text: string): number => {
  const chars = [...text.toUpperCase()];
  if (chars.length === 0) return 0;

  let units = 0;
  chars.forEach((char, i) => {
    const glyph = GLYPHS[char];
    units += (glyph?.[0].length ?? 0) + (i > 0 ? PIXEL_TRACKING : 0);
  });
  return units;
};

/** Builds the whole string as one path plus its unit width. */
export const buildPixelText = (text: string): { d: string; units: number } => {
  let d = "";
  let cursor = 0;

  [...text.toUpperCase()].forEach((char, i) => {
    if (i > 0) cursor += PIXEL_TRACKING;
    const glyph = glyphPath(char, cursor);
    d += glyph.d;
    cursor += glyph.width;
  });

  return { d, units: cursor };
};
